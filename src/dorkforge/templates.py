def by_id(template_id: str) -> dict[str, Any]:
    for template in TEMPLATES:
        if template["id"] == template_id:
            return template
    raise KeyError(template_id)


def by_risk(risk: str) -> list[dict[str, Any]]:
    return [template for template in TEMPLATES if template["risk"] == risk]


def by_tag(tag: str) -> list[dict[str, Any]]:
    return [template for template in TEMPLATES if tag in template.get("tags", [])]
